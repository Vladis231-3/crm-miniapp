/**
 * Обучающий сценарий мини-помощника (training-версия CRM).
 *
 * Шаги тура ищут элементы по CSS-селекторам (`data-training` атрибуты,
 * проставленные на ключевых элементах экранов). Если элемент на текущем
 * экране не найден — шаг пропускается, поэтому один и тот же скрипт
 * работает на экране входа, в клиентском кабинете и в админ-панели.
 */

export interface TourStep {
  /** CSS-селектор подсвечиваемого элемента. Шаг без target — просто текст. */
  target?: string;
  /** Короткий заголовок шага */
  title: string;
  /** Объяснение, за что отвечает элемент */
  text: string;
}

export interface IntroSlide {
  title: string;
  text: string;
}

